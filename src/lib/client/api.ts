/** Browser-side API wrappers, image preparation and error states. */

import type { AnalyzeResponse, CircuitGraph, SimulateResponse } from '../types';

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
export const MAX_EDGE = 2048;

export class ApiError extends Error {
  constructor(public status: number, message: string) { super(message); }
}

/**
 * Downscales to 2048px on the longest edge before upload (FR-1.6).
 * A 12MP phone photo becomes about 400KB, which is the difference between a
 * four-second upload and an instant one on a conference wifi.
 */
export async function prepareImage(file: File): Promise<{ blob: Blob; previewUrl: string; width: number; height: number }> {
  if (file.size > MAX_UPLOAD_BYTES * 3) {
    throw new ApiError(413, 'That image is too large. Try one under 10MB.');
  }
  const bitmap = await createImageBitmap(file).catch(() => null);
  if (!bitmap) {
    // HEIC and anything the browser cannot decode is sent as-is; the server
    // normalises it with sharp.
    if (file.size > MAX_UPLOAD_BYTES) throw new ApiError(413, 'That image is too large. Try one under 10MB.');
    return { blob: file, previewUrl: URL.createObjectURL(file), width: 0, height: 0 };
  }

  const scale = Math.min(1, MAX_EDGE / Math.max(bitmap.width, bitmap.height));
  const width = Math.round(bitmap.width * scale);
  const height = Math.round(bitmap.height * scale);
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) return { blob: file, previewUrl: URL.createObjectURL(file), width: bitmap.width, height: bitmap.height };
  ctx.imageSmoothingQuality = 'high';
  ctx.drawImage(bitmap, 0, 0, width, height);
  bitmap.close();

  const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, 'image/jpeg', 0.92));
  if (!blob) return { blob: file, previewUrl: URL.createObjectURL(file), width, height };
  return { blob, previewUrl: URL.createObjectURL(blob), width, height };
}

async function readError(res: Response, fallback: string): Promise<never> {
  const body = await res.json().catch(() => null);
  throw new ApiError(res.status, body?.error ?? fallback);
}

export async function analyze(blob: Blob, sampleId?: string, signal?: AbortSignal): Promise<AnalyzeResponse> {
  const form = new FormData();
  form.append('image', blob, 'sketch.jpg');
  if (sampleId) form.append('sample', sampleId);
  const res = await fetch('/api/analyze', { method: 'POST', body: form, signal });
  if (!res.ok) await readError(res, 'Something went wrong analysing that. Try again.');
  return res.json();
}

export async function simulate(graph: CircuitGraph, signal?: AbortSignal): Promise<SimulateResponse> {
  const res = await fetch('/api/simulate', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(graph),
    signal,
  });
  if (!res.ok) await readError(res, 'That edit could not be simulated.');
  return res.json();
}

export interface SampleInfo {
  id: string; title: string; description: string; image: string; difficulty: string;
}

export async function fetchStatus(): Promise<{ live: boolean; samples: SampleInfo[] }> {
  const res = await fetch('/api/analyze');
  if (!res.ok) return { live: false, samples: [] };
  return res.json();
}

/** Exports the circuit as a SPICE netlist, so it can be taken to a real simulator (US-12). */
export function toSpiceNetlist(graph: CircuitGraph): string {
  const nodeOf = new Map<string, string>();
  const groundNet = graph.nets.find((n) => n.is_ground)?.id;
  graph.nets.forEach((net, i) => {
    nodeOf.set(net.id, net.id === groundNet ? '0' : String(i + 1));
  });
  const nodeFor = (pin: string) => {
    const net = graph.nets.find((n) => n.pins.includes(pin));
    return net ? nodeOf.get(net.id)! : '0';
  };

  const lines = ['* Generated by Sketch -> Circuit', ''];
  const models = new Set<string>();
  for (const c of graph.components) {
    const v = c.value ?? '';
    switch (c.type) {
      case 'resistor':
        lines.push(`R${c.id} ${nodeFor(`${c.id}.a`)} ${nodeFor(`${c.id}.b`)} ${v || '1k'}`); break;
      case 'battery':
        lines.push(`V${c.id} ${nodeFor(`${c.id}.pos`)} ${nodeFor(`${c.id}.neg`)} DC ${v || '9'}`); break;
      case 'led':
        lines.push(`D${c.id} ${nodeFor(`${c.id}.anode`)} ${nodeFor(`${c.id}.cathode`)} LED_${(v || 'red').toUpperCase()}`);
        models.add(`.model LED_${(v || 'red').toUpperCase()} D(IS=1e-15 N=2.3 RS=15)`);
        break;
      case 'diode':
        lines.push(`D${c.id} ${nodeFor(`${c.id}.anode`)} ${nodeFor(`${c.id}.cathode`)} DSILICON`);
        models.add('.model DSILICON D(IS=1e-14 N=1)');
        break;
      case 'capacitor':
        lines.push(`C${c.id} ${nodeFor(`${c.id}.a`)} ${nodeFor(`${c.id}.b`)} ${v || '100n'}`); break;
      case 'capacitor_electrolytic':
        lines.push(`C${c.id} ${nodeFor(`${c.id}.pos`)} ${nodeFor(`${c.id}.neg`)} ${v || '10u'}`); break;
      case 'inductor':
        lines.push(`L${c.id} ${nodeFor(`${c.id}.a`)} ${nodeFor(`${c.id}.b`)} ${v || '1m'}`); break;
      case 'switch':
        lines.push(`R${c.id} ${nodeFor(`${c.id}.a`)} ${nodeFor(`${c.id}.b`)} ${(v || 'closed') === 'open' ? '1e9' : '1m'} ; ${c.id} switch`);
        break;
      case 'motor': case 'buzzer': {
        const [pa, pb] = c.type === 'motor' ? ['a', 'b'] : ['pos', 'neg'];
        lines.push(`R${c.id} ${nodeFor(`${c.id}.${pa}`)} ${nodeFor(`${c.id}.${pb}`)} ${v || (c.type === 'motor' ? '10' : '100')} ; ${c.type}`);
        break;
      }
      default:
        lines.push(`* ${c.id} (${c.type}) is not represented in this netlist`);
    }
  }
  lines.push('', ...[...models], '', '.op', '.end', '');
  return lines.join('\n');
}
